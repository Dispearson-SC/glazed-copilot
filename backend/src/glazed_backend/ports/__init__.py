"""Ports: the interfaces the application depends on. Adapters implement them."""
from __future__ import annotations

from datetime import date, datetime
from typing import Any, Protocol

from ..domain import Alert, AlertState, BacktestRun, Case, Execution, Experience, Proposal, TraceEvent


class MetricsPort(Protocol):
    """Every number the system shows comes from here. Every read enforces date <= as_of
    (except backtest_day, which reads outcomes after the replayed day on purpose)."""

    def stores(self) -> list[dict[str, Any]]: ...
    def kpis(self, store_id: str, as_of: date, date_from: date, date_to: date) -> dict[str, Any]: ...
    def day_summary(self, store_id: str, as_of: date, day: date) -> dict[str, Any]: ...
    def issues(self, store_id: str, as_of: date, limit: int = 5) -> list[dict[str, Any]]: ...
    def inventory_projection(self, store_id: str, as_of: date, sku: str, horizon: int = 7) -> dict[str, Any]: ...
    def order_plan(self, store_id: str, as_of: date) -> dict[str, Any]: ...
    def supplier_performance(self, store_id: str, as_of: date) -> list[dict[str, Any]]: ...
    def promo_evaluation(self, store_id: str, as_of: date, promo_id: str) -> dict[str, Any]: ...
    def observed_outcome(self, store_id: str, as_of: date, action_type: str, params: dict[str, Any]) -> dict[str, Any] | None:
        """Measured net of an executed decision over its horizon (replay of the calibration rule), or None when the
        action cannot be measured or the window is incomplete at as_of."""
        ...
    def promo_audit(self, store_id: str, as_of: date, department: str, discount_pct: float) -> dict[str, Any]: ...
    def history(self, store_id: str, as_of: date) -> dict[str, Any]: ...
    def backtest_day(self, store_id: str, day: date, policy: str) -> dict[str, Any]:
        """Replay one day: {current: {waste_usd, lost_sales_usd}, policy: {...}} using only data <= day
        for decisions and the following day for outcomes."""
        ...


class CorePort(Protocol):
    def create_conversation(self, case_id: str, store_id: str) -> str: ...
    def send_turn(self, conversation_id: str, store_id: str, text: str) -> str: ...
    def get_turn(self, turn_id: str, store_id: str) -> dict[str, Any]: ...
    def list_transcript(self, conversation_id: str, store_id: str) -> list[dict[str, Any]]: ...


class CaseRepository(Protocol):
    def add(self, case: Case) -> None: ...
    def update(self, case: Case) -> None: ...
    def get(self, case_id: str) -> Case | None: ...
    def get_by_issue_key(self, issue_key: str) -> Case | None: ...
    def get_by_conversation(self, conversation_id: str) -> Case | None: ...
    def list(self, store_id: str | None = None) -> list[Case]: ...


class AlertRepository(Protocol):
    def add(self, alert: Alert) -> None: ...
    def update(self, alert: Alert) -> None: ...
    def get(self, alert_id: str) -> Alert | None: ...
    def get_by_issue_key(self, issue_key: str) -> Alert | None: ...
    def list(self, store_id: str | None = None, state: AlertState | None = None) -> list[Alert]: ...


class ProposalRepository(Protocol):
    def add(self, proposal: Proposal) -> None: ...
    def update(self, proposal: Proposal) -> None: ...
    def get(self, proposal_id: str) -> Proposal | None: ...
    def find_by_idempotency_key(self, case_id: str, key: str) -> Proposal | None: ...
    def list(self, case_id: str | None = None, store_id: str | None = None,
             status: str | None = None) -> list[Proposal]: ...


class ExecutionRepository(Protocol):
    def add(self, execution: Execution) -> None: ...
    def list(self, case_id: str) -> list[Execution]: ...


class BacktestRepository(Protocol):
    def add(self, run: BacktestRun) -> None: ...
    def get(self, run_id: str) -> BacktestRun | None: ...
    def list(self, case_id: str | None = None) -> list[BacktestRun]: ...


class TracePort(Protocol):
    def record(self, event: TraceEvent) -> None: ...
    def list(self, case_id: str | None = None, store_id: str | None = None) -> list[TraceEvent]: ...


class Clock(Protocol):
    def now(self) -> datetime: ...


class ExperienceMemoryPort(Protocol):
    """Per-store experience memory. Writes come only from code, never from an agent's free text."""

    def recall(self, store_id: str, query: str, limit: int = 5) -> list["Experience"]: ...
    def remember(self, store_id: str, experience: "Experience") -> None: ...


class AssistantRepository(Protocol):
    def get(self, store_id: str) -> str | None: ...
    def set(self, store_id: str, assistant_id: str) -> None: ...
